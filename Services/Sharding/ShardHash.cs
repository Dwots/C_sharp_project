using System.Text;

namespace GameLibApi.Services.Sharding;

/// <summary>
/// Хеш-функция для шардирования.
///
/// Встроенный string.GetHashCode() здесь использовать НЕЛЬЗЯ: в .NET он
/// намеренно рандомизируется при каждом запуске процесса — защита от атак
/// на хеш-таблицы. Для шардирования это означало бы, что после перезапуска
/// сервиса записи «переехали» бы на другие шарды сами собой и перестали
/// находиться.
///
/// Нужна детерминированная функция: одинаковый результат при любом запуске,
/// на любой машине, в любой версии среды. Взят FNV-1a — простой, быстрый
/// и хорошо перемешивающий алгоритм.
/// </summary>
public static class ShardHash
{
    // Константы алгоритма FNV-1a для 32 бит, заданы его спецификацией.
    private const uint OffsetBasis = 2166136261;
    private const uint Prime = 16777619;

    /// <summary>
    /// Считает 32-битный хеш строки. Алгоритм: взять начальное значение и для
    /// каждого байта сделать XOR, затем умножить на простое число. Умножение
    /// «размазывает» изменение одного байта по всему результату, поэтому
    /// соседние ключи дают совершенно разные хеши.
    /// </summary>
    public static uint Compute(string value)
    {
        var hash = OffsetBasis;

        foreach (var b in Encoding.UTF8.GetBytes(value))
        {
            hash ^= b;
            hash *= Prime;
        }

        return hash;
    }

    /// <summary>
    /// Хеш ключа шардирования. user_id приводится к строке, чтобы одна и та же
    /// функция годилась и для числовых ключей, и для строковых (email, tenant).
    /// </summary>
    public static uint Compute(int shardKey) => Compute(shardKey.ToString());
}
